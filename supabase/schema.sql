-- 바코드 매장 관리 - Supabase schema
-- Run this in the Supabase SQL editor only when rebuilding a deleted project.
-- If the original project is only paused, resume it instead; do not recreate it.

create table if not exists public.store_key (
  store_key text primary key,
  store_name text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.store_key enable row level security;

grant usage on schema public to anon;
grant select on public.store_key to anon;

drop policy if exists store_key_anon_select on public.store_key;
create policy store_key_anon_select
  on public.store_key
  for select
  to anon
  using (true);

-- Creates the per-store tables used by the app:
--   <store_key>_list
--   <store_key>_category
create or replace function public.create_store_tables(p_store_key text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_list_table text := p_store_key || '_list';
  v_category_table text := p_store_key || '_category';
begin
  if p_store_key !~ '^[A-Za-z0-9_]+$' then
    raise exception 'store_key must contain only letters, numbers, and underscores';
  end if;

  execute format($sql$
    create table if not exists public.%I (
      id bigint generated by default as identity primary key,
      store_key text not null,
      barcode text not null,
      barcode_image_url text,
      product_name text,
      product_image_url text,
      expiry_date date not null,
      category_id bigint,
      memo text,
      created_at timestamptz not null default now()
    )
  $sql$, v_list_table);

  execute format($sql$
    create table if not exists public.%I (
      id bigint generated by default as identity primary key,
      store_key text not null,
      category_name text not null,
      display_order integer not null default 0,
      is_active boolean not null default true,
      created_at timestamptz not null default now()
    )
  $sql$, v_category_table);

  execute format(
    'create index if not exists %I on public.%I (expiry_date)',
    v_list_table || '_expiry_idx',
    v_list_table
  );

  execute format(
    'create index if not exists %I on public.%I (category_id)',
    v_list_table || '_category_idx',
    v_list_table
  );

  execute format('alter table public.%I enable row level security', v_list_table);
  execute format('alter table public.%I enable row level security', v_category_table);

  execute format('grant all on public.%I to anon', v_list_table);
  execute format('grant all on public.%I to anon', v_category_table);
  execute 'grant usage, select on all sequences in schema public to anon';

  -- The recovered app uses a store key instead of Supabase Auth.
  -- These permissive policies are required for the current client to work.
  execute format(
    'drop policy if exists %I on public.%I',
    v_list_table || '_anon_all',
    v_list_table
  );
  execute format(
    'create policy %I on public.%I for all to anon using (true) with check (true)',
    v_list_table || '_anon_all',
    v_list_table
  );

  execute format(
    'drop policy if exists %I on public.%I',
    v_category_table || '_anon_all',
    v_category_table
  );
  execute format(
    'create policy %I on public.%I for all to anon using (true) with check (true)',
    v_category_table || '_anon_all',
    v_category_table
  );
end;
$$;

