-- 사용 순서:
--   1. https://supabase.com/dashboard 에서 무료 프로젝트를 만듭니다.
--   2. SQL Editor에서 이 파일 전체를 붙여넣고 Run 합니다.
--   3. Project Settings > API에서 Project URL과 anon/publishable key를 복사합니다.
--   4. 프로젝트 루트의 .env.example을 .env로 복사하고 두 값을 넣습니다.
--   5. npm run dev 후 매장 키 `seven01`로 로그인합니다.
--
-- 이 스크립트는 다시 실행해도 안전하도록 작성했습니다.

create table if not exists public.store_key (
  store_key text primary key,
  store_name text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.store_key enable row level security;

grant usage on schema public to anon;
grant select on public.store_key to anon;

drop policy if exists store_key_anon_select on public.store_key;
create policy store_key_anon_select
  on public.store_key
  for select
  to anon
  using (true);

create or replace function public.create_store_tables(p_store_key text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_list_table text := p_store_key || '_list';
  v_category_table text := p_store_key || '_category';
begin
  if p_store_key !~ '^[A-Za-z0-9_]+$' then
    raise exception 'store_key must contain only letters, numbers, and underscores';
  end if;

  execute format($sql$
    create table if not exists public.%I (
      id bigint generated by default as identity primary key,
      store_key text not null,
      barcode text not null,
      barcode_image_url text,
      product_name text,
      product_image_url text,
      expiry_date date not null,
      category_id bigint,
      memo text,
      created_at timestamptz not null default now()
    )
  $sql$, v_list_table);

  execute format($sql$
    create table if not exists public.%I (
      id bigint generated by default as identity primary key,
      store_key text not null,
      category_name text not null,
      display_order integer not null default 0,
      is_active boolean not null default true,
      created_at timestamptz not null default now()
    )
  $sql$, v_category_table);

  execute format(
    'create index if not exists %I on public.%I (expiry_date)',
    v_list_table || '_expiry_idx',
    v_list_table
  );

  execute format(
    'create index if not exists %I on public.%I (category_id)',
    v_list_table || '_category_idx',
    v_list_table
  );

  execute format('alter table public.%I enable row level security', v_list_table);
  execute format('alter table public.%I enable row level security', v_category_table);

  execute format('grant all on public.%I to anon', v_list_table);
  execute format('grant all on public.%I to anon', v_category_table);
  execute 'grant usage, select on all sequences in schema public to anon';

  execute format(
    'drop policy if exists %I on public.%I',
    v_list_table || '_anon_all',
    v_list_table
  );
  execute format(
    'create policy %I on public.%I for all to anon using (true) with check (true)',
    v_list_table || '_anon_all',
    v_list_table
  );

  execute format(
    'drop policy if exists %I on public.%I',
    v_category_table || '_anon_all',
    v_category_table
  );
  execute format(
    'create policy %I on public.%I for all to anon using (true) with check (true)',
    v_category_table || '_anon_all',
    v_category_table
  );
end;
$$;

-- 데모 매장 생성 (매장 이름은 나중에 바꿔도 됩니다)
insert into public.store_key (store_key, store_name, is_active)
values ('seven01', '내 매장', true)
on conflict (store_key) do update set is_active = true;

select public.create_store_tables('seven01');

-- 카테고리 샘플
insert into public.seven01_category (store_key, category_name, display_order, is_active)
select v.store_key, v.category_name, v.display_order, true
from (
  values
    ('seven01', '음료', 0),
    ('seven01', '유제품', 1),
    ('seven01', '간식', 2)
) as v(store_key, category_name, display_order)
where not exists (
  select 1
  from public.seven01_category c
  where c.store_key = v.store_key
    and c.category_name = v.category_name
);

